"""Large-cap universe for SEC 8-K events (S&P 500 + Nasdaq-100).

User policy (2026-11-07): SEC 8-K events are large-cap only. An earnings
season otherwise floods the radar with 500+ mostly small-cap filings.

The ticker list lives in ``config/sec_large_cap_universe.json`` and is
regenerated by ``scripts/update_sec_universe.py`` (Wikipedia S&P 500 table
+ Nasdaq's official Nasdaq-100 API). Ticker -> CIK resolution happens at
runtime against SEC's official company_tickers.json; no CIKs are stored.

Loading is fail-open: a missing/unreadable universe file yields ``None``
and callers must skip filtering rather than dropping every SEC event.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

UNIVERSE_FILENAME = "sec_large_cap_universe.json"


def normalize_us_ticker(ticker: str) -> str:
    """Normalize a US ticker to SEC EDGAR style (BRK.B -> BRK-B)."""
    return str(ticker or "").strip().upper().replace(".", "-")


def default_universe_path() -> Path:
    """Repo-root config path, resolved from this file's location."""
    return Path(__file__).resolve().parents[2] / "config" / UNIVERSE_FILENAME


def load_large_cap_universe(path: Optional[Path | str] = None) -> Optional[frozenset[str]]:
    """Load normalized large-cap tickers, or None when unavailable."""
    universe_path = Path(path) if path is not None else default_universe_path()
    try:
        payload = json.loads(universe_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    tickers = payload.get("tickers") if isinstance(payload, dict) else None
    if not isinstance(tickers, list) or not tickers:
        return None
    normalized = {normalize_us_ticker(t) for t in tickers if str(t).strip()}
    return frozenset(normalized) if normalized else None
